# 사전에 이름이 있지만 질문에서는 제품 종류를 뜻하는 말(성분으로 보지 않음)
_NOT_INGREDIENT = {"크림", "로션", "세럼", "토너", "에센스", "오일", "워터", "젤", "밤", "앰플", "미스트", "팩", "마스크", "클렌저", "선크림"}
_PARTICLES = re.compile(r"(이랑|랑|이나|나|은|는|이|가|을|를|도|의|에|에서|으로|로|과|와|만|이요|요)$")
_matcher = None


def _m():
    global _matcher
    _matcher = _matcher or pipeline.Matcher()
    return _matcher


def find_ingredients(question: str, limit: int = 5) -> list[dict]:
    """질문 속 성분 이름을 식약처 사전에서 찾는다(정확히 일치하는 것만, 조사는 떼고). 지어내지 않는다."""
    hits, seen = [], set()
    for raw in re.findall(r"[가-힣A-Za-z0-9\-]+", question):
        for w in (raw, _PARTICLES.sub("", raw)):
            if len(w) < 2:
                continue
            h = _m().exact(w) if w not in _NOT_INGREDIENT else None
            if h and h["kor"] not in seen:
                seen.add(h["kor"])
                hits.append({"kor": h["kor"], "inci": h.get("inci", ""), "families": fam.tag(h["kor"], h.get("inci", ""))})
                break
        if len(hits) >= limit:
            break
    return hits


def families_in(question: str) -> list[str]:
    """질문에 계열 이름이나 그 계열 성분 이름이 나오면 그 계열."""
    q = question.replace(" ", "")
    return list(dict.fromkeys([f for f in fam.RULES if f.replace(" ", "") in q] + fam.tag(question)))


def sources_for(question: str, routine_families: list[str]) -> dict:
    """모델에 줄 근거 자료 묶음. id → 문장. 모델은 이 id로만 근거를 단다."""
    src = {k: f"{q} {a}" for k, (q, a) in FAQ.items()}
    ings = find_ingredients(question)
    fams = list(dict.fromkeys(families_in(question) + [f for i in ings for f in i["families"]] + list(routine_families)))
    for f in fams:
        if f in FAMILY_INFO:
            src[f"family-{f}"] = f"{f}: {FAMILY_INFO[f]} {WHY_MARKED}"
    for i in ings:
        fam_txt = f" 낯씨의 성분 계열로는 {', '.join(i['families'])}에 들어가요." if i["families"] else " 낯씨가 따로 표시하는 성분 계열에는 들어가지 않아요."
        inci = f"(국제 표기 {i['inci']})" if i["inci"] else ""
        src[f"ingredient-{i['kor']}"] = f"{i['kor']}{inci}는 식약처 화장품 원료성분 사전에 있는 이름이에요.{fam_txt}"
    return src
